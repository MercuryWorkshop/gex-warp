#!/usr/bin/env python3
"""Write crates/gex-kernel/src/darwin/nr.rs from XNU's own tables.

    scripts/gen-darwin-syscalls.py XNU_SOURCE

XNU_SOURCE is a checkout of apple-oss-distributions/xnu. The BSD system
calls come from bsd/kern/syscalls.master, the Mach traps from
osfmk/kern/syscall_sw.c. Only numbers and names are taken.
"""
import re
import subprocess
import sys

xnu = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "crates/gex-kernel/src/darwin/nr.rs"
tag = subprocess.run(["git", "-C", xnu, "describe", "--tags", "--always"], capture_output=True, text=True).stdout.strip()

bsd = {}
for line in open(f"{xnu}/bsd/kern/syscalls.master"):
    m = re.match(r"^(\d+)\s+\w+\s+\w+\s+\{\s*(.*?)\s*\}", line)
    if not m:
        continue
    n, proto = int(m.group(1)), m.group(2)
    f = re.match(r"[\w\s\*]*?\b(\w+)\s*\(", proto)
    name = f.group(1)
    if name in ("nosys", "enosys"):
        continue
    # The first definition of a number is the one a release kernel has
    # (`#if SOCKETS`, `#if CONFIG_...` come before their `#else nosys`).
    bsd.setdefault(n, name)

mach = {}
for line in open(f"{xnu}/osfmk/kern/syscall_sw.c"):
    m = re.match(r"^/\*\s*(\d+)\s*\*/\s*MACH_TRAP\(\s*(\w+)", line)
    if m and m.group(2) != "kern_invalid":
        mach[int(m.group(1))] = m.group(2)

def const(name):
    return re.sub(r"^_+", "", name).upper()

with open(out, "w") as o:
    o.write(f"//! XNU's system call and Mach trap numbers ({tag}).\n")
    o.write("//!\n//! Generated by scripts/gen-darwin-syscalls.py from XNU's\n")
    o.write("//! bsd/kern/syscalls.master and osfmk/kern/syscall_sw.c: do not edit.\n\n")
    o.write("#![allow(dead_code)]\n\n")
    seen = set()
    for n in sorted(bsd):
        c = const(bsd[n])
        # `sys_close` and the like are the kernel's spelling of `close`.
        c = re.sub(r"^SYS_", "", c)
        if c in seen:
            c = f"{c}_{n}"
        seen.add(c)
        o.write(f"pub const {c}: u64 = {n};\n")
    o.write("\n/// A BSD system call's name, as syscalls.master spells it.\n")
    o.write("pub fn name(n: u64) -> Option<&'static str> {\n    Some(match n {\n")
    for n in sorted(bsd):
        o.write(f"        {n} => \"{re.sub(r'^sys_', '', bsd[n])}\",\n")
    o.write("        _ => return None,\n    })\n}\n")
    o.write("\n/// Mach traps, by their positive number (a guest passes the negative).\npub mod trap {\n")
    seen = set()
    for n in sorted(mach):
        c = const(mach[n])
        c = re.sub(r"^KERNELRPC_", "", c)
        c = re.sub(r"_TRAP$", "", c)
        if c in seen:
            c = f"{c}_{n}"
        seen.add(c)
        o.write(f"    pub const {c}: u64 = {n};\n")
    o.write("\n    /// A Mach trap's name, as syscall_sw.c spells it.\n")
    o.write("    pub fn name(n: u64) -> Option<&'static str> {\n        Some(match n {\n")
    for n in sorted(mach):
        o.write(f"            {n} => \"{mach[n]}\",\n")
    o.write("            _ => return None,\n        })\n    }\n}\n")
